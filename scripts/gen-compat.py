#!/usr/bin/env python3
"""Compat libraries the stock vendor blobs link, built from AOSP VNDK snapshots and your stock vendor image.

- libprotobuf-cpp-lite-3.9.1-vendorcompat: stock /vendor/lib*/libprotobuf-cpp-lite-3.9.1.so.
- libutils-v32: AOSP prebuilts/vndk/v32 libutils.so, SONAME renamed, NEEDED libprocessgroup_shim.so added
  (the shim in mt6835-common/compat restores libprocessgroup symbols the v32 libutils uses).
- libstagefright_foundation-v33: AOSP prebuilts/vndk/v33 libstagefright_foundation.so, SONAME renamed.

Usage, from the AOSP tree root after extracting the blobs:
    python3 <this repo>/scripts/gen-compat.py <path to your extracted stock /vendor>
Output: vendor/motorola/mt6835-common-vegas26/aosp-compat (generated, contains a stock library: never publish it).
"""
import os, shutil, subprocess, sys

STOCK = sys.argv[1] if len(sys.argv) > 1 else sys.exit(__doc__)
VNDK = "prebuilts/vndk"
PATCHELF = "prebuilts/extract-tools/linux-x86/bin/patchelf-0_18"
OUT = "vendor/motorola/mt6835-common-vegas26/aosp-compat"

ARCH = {"arm64": ("lib64", "arch-arm64-armv8-a"), "arm": ("lib", "arch-arm-armv8-a")}

LIBS = [
    # name, stem, source kind, vndk ver, vndk subdir, add_needed, extra props
    ("libprotobuf-cpp-lite-3.9.1-vendorcompat", "libprotobuf-cpp-lite-3.9.1", "stock", None, None, [],
     '    vendor: true,\n'),
    ("libutils-v32", "libutils-v32", "vndk", "v32", "vndk-sp", ["libprocessgroup_shim.so"],
     '    vendor: true,\n    shared_libs: ["libc++", "libcutils", "liblog", "libprocessgroup", "libprocessgroup_shim", "libvndksupport"],\n'),
    ("libstagefright_foundation-v33", "libstagefright_foundation-v33", "vndk", "v33", "vndk-core", [],
     '    system_ext_specific: true,\n    vendor_available: true,\n    shared_libs: ["libc++", "libcutils", "liblog", "libutils"],\n'),
]

if not os.access(PATCHELF, os.X_OK):
    sys.exit(f"missing {PATCHELF}: sync prebuilts/extract-tools (local_manifests/vegas26-aosp17.xml)")
shutil.rmtree(OUT, ignore_errors=True)
bp = ["// Generated by gen-compat.py from AOSP VNDK snapshots and the stock vendor image. Do not publish.\n"]
for name, stem, kind, ver, sub, add_needed, props in LIBS:
    targets = []
    for arch, (libdir, archdir) in ARCH.items():
        if kind == "stock":
            src = f"{STOCK}/{libdir}/{stem}.so"
        else:
            base = stem.rsplit("-", 1)[0]
            src = f"{VNDK}/{ver}/arm64/{archdir}/shared/{sub}/{base}.so"
        if not os.path.exists(src):
            continue
        dst = f"{OUT}/{arch}/{stem}.so"
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy(src, dst)
        os.chmod(dst, 0o644)
        if kind == "vndk":
            subprocess.check_call([PATCHELF, "--set-soname", f"{stem}.so", dst])
            for n in add_needed:
                subprocess.check_call([PATCHELF, "--add-needed", n, dst])
        targets.append(f'        android_{arch}: {{ srcs: ["{arch}/{stem}.so"] }},')
    if not targets:
        sys.exit(f"no source found for {name}")
    bp.append(f'''cc_prebuilt_library_shared {{
    name: "{name}",
    stem: "{stem}",
{props}    ignore_max_page_size: true,
    strip: {{ none: true }},
    check_elf_files: false,
    compile_multilib: "both",
    target: {{
{chr(10).join(targets)}
    }},
}}
''')
open(f"{OUT}/Android.bp", "w").write("\n".join(bp))
print("compat libs:", [l[0] for l in LIBS])
